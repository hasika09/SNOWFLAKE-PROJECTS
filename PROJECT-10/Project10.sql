    U.SEGMENT,

    U.EFFECTIVE_DATE,

    DATE '9999-12-31',

    TRUE

FROM STG_CUSTOMER_UPDATES U

JOIN DIM_CUSTOMER_TYPE6 C
    ON U.CUSTOMER_ID = C.CUSTOMER_ID

WHERE C.IS_CURRENT = FALSE

  AND C.EXPIRY_DATE = DATEADD(
        DAY,
        -1,
