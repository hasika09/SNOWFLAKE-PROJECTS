    PREVIOUS_MEMBERSHIP,
    HISTORICAL_MEMBERSHIP,
    SEGMENT,
    EFFECTIVE_DATE,
    EXPIRY_DATE,
    IS_CURRENT
)
SELECT
    U.CUSTOMER_ID,
    U.CUSTOMER_NAME,
    U.CITY,
    U.STATE,
    U.MEMBERSHIP AS CURRENT_MEMBERSHIP,

    C.CURRENT_MEMBERSHIP AS PREVIOUS_MEMBERSHIP,

