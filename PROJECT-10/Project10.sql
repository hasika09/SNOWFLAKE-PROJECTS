    DATE '2026-01-01' AS EFFECTIVE_DATE,
    DATE '9999-12-31' AS EXPIRY_DATE,
    TRUE AS IS_CURRENT
FROM STG_CUSTOMERS_INITIAL;


SELECT
    COUNT(*) AS TOTAL_TYPE6_RECORDS,
    COUNT_IF(IS_CURRENT = TRUE) AS CURRENT_RECORDS
FROM DIM_CUSTOMER_TYPE6;

SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    STATE,
    CURRENT_MEMBERSHIP,
