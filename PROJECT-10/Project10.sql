/* =====================================================================
   TASK 13 — VALIDATE INITIAL TYPE 3 RECORDS
   ===================================================================== */

SELECT
    COUNT(*) AS TYPE3_RECORD_COUNT
FROM DIM_CUSTOMER_TYPE3;


SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    CURRENT_MEMBERSHIP,
    PREVIOUS_MEMBERSHIP
FROM DIM_CUSTOMER_TYPE3
ORDER BY CUSTOMER_ID;

SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.CURRENT_MEMBERSHIP AS OLD_MEMBERSHIP,
    U.MEMBERSHIP AS NEW_MEMBERSHIP
FROM DIM_CUSTOMER_TYPE3 C
JOIN STG_CUSTOMER_UPDATES U
    ON C.CUSTOMER_ID = U.CUSTOMER_ID
WHERE C.CURRENT_MEMBERSHIP <> U.MEMBERSHIP
ORDER BY C.CUSTOMER_ID;

UPDATE DIM_CUSTOMER_TYPE3 C

SET
    PREVIOUS_MEMBERSHIP = C.CURRENT_MEMBERSHIP,
    CURRENT_MEMBERSHIP = U.MEMBERSHIP,
    CUSTOMER_NAME = U.CUSTOMER_NAME,
    CITY = U.CITY,
    STATE = U.STATE,
    SEGMENT = U.SEGMENT

FROM STG_CUSTOMER_UPDATES U

WHERE C.CUSTOMER_ID = U.CUSTOMER_ID
  AND C.CURRENT_MEMBERSHIP <> U.MEMBERSHIP;

SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    CURRENT_MEMBERSHIP,
    PREVIOUS_MEMBERSHIP
FROM DIM_CUSTOMER_TYPE3
ORDER BY CUSTOMER_ID;

SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CURRENT_MEMBERSHIP,
    PREVIOUS_MEMBERSHIP
FROM DIM_CUSTOMER_TYPE3
WHERE CUSTOMER_ID = 101;

SELECT
    COUNT(*) AS SCD_TYPE3_RECORD_COUNT
FROM DIM_CUSTOMER_TYPE3;

