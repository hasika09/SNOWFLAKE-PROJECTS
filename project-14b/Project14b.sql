WITH BRONZE_TOTAL AS (
    SELECT
        SUM(RAW_PAYLOAD:amount::NUMBER(18,2)) AS BRONZE_GROSS_SUM
    FROM BRONZE_PAYMENT_PAYLOADS
),
SILVER_TOTAL AS (
    SELECT
        SUM(GROSS_AMOUNT) AS SILVER_GROSS_SUM
    FROM SILVER_CLEANED_TRANSACTIONS
),
GOLD_TOTAL AS (
    SELECT
        SUM(TOTAL_APPROVED_GROSS) AS GOLD_GROSS_SUM
    FROM GOLD_MERCHANT_SETTLEMENTS
)
SELECT
    B.BRONZE_GROSS_SUM,
    S.SILVER_GROSS_SUM,
    G.GOLD_GROSS_SUM,
    CASE
        WHEN B.BRONZE_GROSS_SUM = S.SILVER_GROSS_SUM
         AND G.GOLD_GROSS_SUM <= S.SILVER_GROSS_SUM
        THEN TRUE
        ELSE FALSE
    END AS DATA_MATCH_FLAG
FROM BRONZE_TOTAL B
CROSS JOIN SILVER_TOTAL S
CROSS JOIN GOLD_TOTAL G;

SELECT
    'BRONZE' AS LAYER,
    SUM(RAW_PAYLOAD:amount::NUMBER(18,2)) AS GROSS_TOTAL
FROM BRONZE_PAYMENT_PAYLOADS

UNION ALL

SELECT
    'SILVER' AS LAYER,
    SUM(GROSS_AMOUNT) AS GROSS_TOTAL
FROM SILVER_CLEANED_TRANSACTIONS

UNION ALL

SELECT
    'GOLD' AS LAYER,
    SUM(TOTAL_APPROVED_GROSS) AS GROSS_TOTAL
FROM GOLD_MERCHANT_SETTLEMENTS;