INSERT INTO BRONZE_PAYMENT_PAYLOADS (
    RAW_PAYLOAD
)
SELECT
    TRY_PARSE_JSON(RAW_RECORD_TEXT)
FROM RAW_PAYMENT_QUEUE
WHERE TRY_PARSE_JSON(RAW_RECORD_TEXT) IS NOT NULL;

SELECT COUNT(*) AS TOTAL_BRONZE_RECORDS_CT
FROM BRONZE_PAYMENT_PAYLOADS;

SELECT
    RAW_PAYLOAD:txn_id::VARCHAR AS TXN_ID,
    RAW_PAYLOAD:txn_time::TIMESTAMP_TZ AS TXN_TIME,
    RAW_PAYLOAD:merchant_id::INTEGER AS MERCHANT_ID,
    RAW_PAYLOAD:merchant_name::VARCHAR AS MERCHANT_NAME,
    RAW_PAYLOAD:amount::NUMBER(18,2) AS AMOUNT,
    RAW_PAYLOAD:fee_pct::NUMBER(10,2) AS FEE_PCT,
    RAW_PAYLOAD:status::VARCHAR AS STATUS
FROM BRONZE_PAYMENT_PAYLOADS
ORDER BY TXN_ID;

CREATE OR REPLACE TABLE SILVER_CLEANED_TRANSACTIONS (
    TXN_ID VARCHAR(50),
    TXN_TIME TIMESTAMP_TZ,
    MERCHANT_ID INTEGER,
    MERCHANT_NAME VARCHAR(100),
    MASKED_CARD VARCHAR(30),
    GROSS_AMOUNT NUMBER(18,2),
    FEE_PCT NUMBER(10,2),
    PROCESSING_FEE NUMBER(18,2),
    NET_SETTLEMENT_AMOUNT NUMBER(18,2),
    STATUS VARCHAR(30)
);

INSERT INTO SILVER_CLEANED_TRANSACTIONS (
    TXN_ID,
    TXN_TIME,
    MERCHANT_ID,
    MERCHANT_NAME,
    MASKED_CARD,
    GROSS_AMOUNT,
    FEE_PCT,
    PROCESSING_FEE,
    NET_SETTLEMENT_AMOUNT,
    STATUS
)
SELECT
    RAW_PAYLOAD:txn_id::VARCHAR,
    RAW_PAYLOAD:txn_time::TIMESTAMP_TZ,
    RAW_PAYLOAD:merchant_id::INTEGER,
    RAW_PAYLOAD:merchant_name::VARCHAR,
    'XXXX-XXXX-XXXX-' || RIGHT(RAW_PAYLOAD:card_number::VARCHAR, 4),
    RAW_PAYLOAD:amount::NUMBER(18,2),
    RAW_PAYLOAD:fee_pct::NUMBER(10,2),
    ROUND(
        RAW_PAYLOAD:amount::NUMBER(18,2)
        * (RAW_PAYLOAD:fee_pct::NUMBER(10,2) / 100),
        2
    ),
    ROUND(
        RAW_PAYLOAD:amount::NUMBER(18,2)
        -
        (
            RAW_PAYLOAD:amount::NUMBER(18,2)
            * (RAW_PAYLOAD:fee_pct::NUMBER(10,2) / 100)
        ),
        2
    ),
    RAW_PAYLOAD:status::VARCHAR
FROM BRONZE_PAYMENT_PAYLOADS;

SELECT
    TXN_ID,
    MERCHANT_ID,
    MERCHANT_NAME,
    MASKED_CARD,
    GROSS_AMOUNT,
    PROCESSING_FEE,
    NET_SETTLEMENT_AMOUNT,
    STATUS
FROM SILVER_CLEANED_TRANSACTIONS
ORDER BY TXN_ID;

