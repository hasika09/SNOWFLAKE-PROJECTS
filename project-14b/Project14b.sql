SELECT
    TXN_ID,
    MERCHANT_NAME,
    GROSS_AMOUNT,
    STATUS
FROM SILVER_CLEANED_TRANSACTIONS
AT (TIMESTAMP => $BEFORE_CORRUPTION_TIME)
WHERE MERCHANT_NAME = 'TechZone'
  AND STATUS = 'APPROVED'
ORDER BY TXN_ID;

UPDATE SILVER_CLEANED_TRANSACTIONS AS CURRENT_DATA
SET STATUS = ORIGINAL_DATA.STATUS
FROM (
    SELECT
        TXN_ID,
        STATUS
    FROM SILVER_CLEANED_TRANSACTIONS
    AT (TIMESTAMP => $BEFORE_CORRUPTION_TIME)
) AS ORIGINAL_DATA
WHERE CURRENT_DATA.TXN_ID = ORIGINAL_DATA.TXN_ID
  AND CURRENT_DATA.MERCHANT_NAME = 'TechZone';

SELECT
    MERCHANT_NAME,
    COUNT_IF(STATUS = 'APPROVED') AS APPROVED_COUNT,
    COUNT_IF(STATUS = 'REFUNDED') AS REFUNDED_COUNT
FROM SILVER_CLEANED_TRANSACTIONS
WHERE MERCHANT_NAME = 'TechZone'
GROUP BY MERCHANT_NAME;

